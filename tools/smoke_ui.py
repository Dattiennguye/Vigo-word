import asyncio
from playwright.async_api import async_playwright
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch()
        pg = await b.new_page(viewport={'width':1366,'height':800})
        logs=[]
        pg.on('console', lambda m: logs.append(m.type+': '+m.text) if m.type in ('error','warning') else None)
        pg.on('pageerror', lambda e: logs.append('PAGEERR: '+str(e)))
        await pg.goto('http://localhost:5077/')
        await pg.select_option('#cells','12000')
        await pg.click('#newgame')
        await pg.wait_for_selector('#game:not(.hidden)', timeout=60000)
        await pg.wait_for_timeout(1200)
        await pg.click('#panel .crow >> nth=2')
        await pg.wait_for_timeout(600)
        await pg.screenshot(path='out/shots/03_picked.png')
        await pg.click('#pickgo')
        await pg.wait_for_timeout(1500)
        await pg.click('#bplay4')
        await pg.wait_for_timeout(9000)
        await pg.screenshot(path='out/shots/04_play.png')
        await pg.click('#tabs button[data-tab=diplo]')
        await pg.wait_for_timeout(500)
        await pg.screenshot(path='out/shots/05_diplo.png')
        await pg.click('#tabs button[data-tab=cities]')
        await pg.wait_for_timeout(500)
        await pg.click('#panel .crow >> nth=0')
        await pg.wait_for_timeout(500)
        await pg.click('#cdemo')
        await pg.wait_for_timeout(2500)
        await pg.screenshot(path='out/shots/06_city.png')
        print('\n'.join(logs[:20]))
        await b.close()
asyncio.run(main())
